#!/usr/bin/env python3
"""R46: same-CPU, interleaved native *runtime* A/B with raw data and disassembly.

Python is a development-only benchmark, not Sutram's compiler or runtime.
No hidden expected-output edits; both compilers must compile, run, agree on
stdout and exit=0 for each source. Different generated bytes are documented.
"""
from __future__ import annotations
import argparse
import csv
import hashlib
import os
from pathlib import Path
import random
import statistics
import subprocess
import tempfile
import time

ROOT=Path(__file__).resolve().parents[1]
SOURCES=[
 "benchmarks/r46_hotcall_stack.sm",
 "benchmarks/r46_hotcall_nested.sm",
 "benchmarks/r46_hotcall_float.sm",
 "benchmarks/r46_hotcall_array.sm",
 "examples/126_numeric_pipeline.sm",
]
def sha(x: bytes):
    return hashlib.sha256(x).hexdigest()
def pct(a, p):
    z=sorted(a)
    point=(len(z)-1)*p
    low=int(point); frac=point-low
    return z[low]*(1-frac)+z[min(len(z)-1,low+1)]*frac
def run(args,timeout=60):
    t=time.perf_counter_ns()
    p=subprocess.run(args,cwd=ROOT,capture_output=True,timeout=timeout)
    return time.perf_counter_ns()-t,p
def profile_program(label,path,source,out):
    _,cp=run([str(path),str(source),str(out)],60)
    if cp.returncode: raise RuntimeError(f"compiler {label} failed on {source}: rc={cp.returncode}, {cp.stdout+cp.stderr!r}")
    data=out.read_bytes()
    if data[:4]!=b"\x7fELF": raise RuntimeError(f"{source}: compiler {label} did not emit ELF")
    return sha(data),len(data)
def disasm_excerpt(path):
    # Actual 64-bit instructions begin after 64-byte ELF + 56-byte PHDR.
    raw=subprocess.check_output(["ndisasm","-b","64","-e","0x78",str(path)],
                                cwd=ROOT,timeout=30,text=True)
    insn=raw.splitlines()
    hits=[i for i,line in enumerate(insn) if "call " in line.lower()]
    items=[]
    for pos in hits[:8]:
        lo=max(0,pos-9); hi=min(len(insn),pos+6)
        items.append("\n".join(insn[lo:hi]))
    return "\n--- CALL BOUNDARY ---\n".join(items) if items else "No direct call found"
def bootstrap_pct(before,after):
    # Paired median ratio, 2,000 reproducible bootstrap resamples.
    rng=random.Random(4609)
    n=len(before)
    draws=[]
    for _ in range(2000):
        idx=[rng.randrange(n) for _ in range(n)]
        b=statistics.median(before[j] for j in idx)
        a=statistics.median(after[j] for j in idx)
        draws.append(100*(b-a)/b)
    return pct(draws,.025),pct(draws,.975)
def main():
    ap=argparse.ArgumentParser()
    ap.add_argument("--before",type=Path,required=True)
    ap.add_argument("--after",type=Path,required=True)
    ap.add_argument("--runs",type=int,default=40)
    ap.add_argument("--warmup",type=int,default=6)
    ap.add_argument("--csv",type=Path,required=True)
    ap.add_argument("--disasm",type=Path,required=True)
    a=ap.parse_args()
    if a.runs<20 or a.warmup<3: ap.error("At least 20 measured pairs / 3 warmups")
    try:
        cpu=min(os.sched_getaffinity(0))
        os.sched_setaffinity(0,{cpu})
    except (AttributeError, OSError, PermissionError):
        cpu=None
    versions={"before":a.before.resolve(),"after":a.after.resolve()}
    for exe in versions.values():
        if not exe.is_file(): raise RuntimeError(f"Missing compiler: {exe}")
    measurements=[];evidence=[]
    with tempfile.TemporaryDirectory(prefix="sutram-r46-") as td:
        dir=Path(td)
        for rel in SOURCES:
            src=ROOT/rel
            compiled={label:dir/(src.stem+"_"+label+".bin") for label in versions}
            signatures={label:profile_program(label,exe,src,compiled[label])
                        for label,exe in versions.items()}
            first={}
            for label,out in compiled.items():
                _,proc=run([str(out)],60)
                if proc.returncode: raise RuntimeError(f"{rel}: {label} native return {proc.returncode}: {proc.stdout+proc.stderr!r}")
                first[label]=proc.stdout
            if first["before"]!=first["after"]:
                raise RuntimeError(f"RUNTIME OUTPUT DIFFERENCE: {rel}: {first!r}")
            evidence.append(f"=== {rel} ===\noutput_sha256={sha(first['before'])}\n"
                            f"before_image={signatures['before']}\nafter_image={signatures['after']}\n"
                            f"generated_byte_identical={signatures['before'][0]==signatures['after'][0]}\n"
                            f"BEFORE MACHINE CODE:\n{disasm_excerpt(compiled['before'])}\n"
                            f"AFTER MACHINE CODE:\n{disasm_excerpt(compiled['after'])}\n")
            pairs={"before":[],"after":[]}
            for iteration in range(-a.warmup,a.runs):
                order=("before","after") if iteration%2==0 else ("after","before")
                for order_idx,label in enumerate(order):
                    ns,r=run([str(compiled[label])],60)
                    if r.returncode!=0 or r.stdout!=first["before"]:
                        raise RuntimeError(f"native drift: {rel} {label} iter={iteration}, rc={r.returncode}, output={r.stdout!r}")
                    if iteration>=0:
                        pairs[label].append(ns)
                        measurements.append({
                          "source":rel,"iteration":iteration,"order":order_idx,
                          "variant":label,"elapsed_ns":ns,"cpu":cpu,
                          "stdout_sha256":sha(r.stdout),"binary_sha256":signatures[label][0],
                          "binary_bytes":signatures[label][1],"exit":r.returncode
                        })
            b,aft=pairs["before"],pairs["after"]
            ci=bootstrap_pct(b,aft)
            bm,am=statistics.median(b),statistics.median(aft)
            print(f"R46_RESULT,{rel},before_median_ms={bm/1e6:.6f},after_median_ms={am/1e6:.6f},"
                  f"speedup_pct={100*(bm-am)/bm:.3f},bootstrap_95_pct=[{ci[0]:.3f},{ci[1]:.3f}],"
                  f"before_p10p90_ms=[{pct(b,.1)/1e6:.4f},{pct(b,.9)/1e6:.4f}],"
                  f"after_p10p90_ms=[{pct(aft,.1)/1e6:.4f},{pct(aft,.9)/1e6:.4f}],"
                  f"minmax_before_ms=[{min(b)/1e6:.4f},{max(b)/1e6:.4f}],"
                  f"minmax_after_ms=[{min(aft)/1e6:.4f},{max(aft)/1e6:.4f}],"
                  f"pairs={a.runs},images_same={signatures['before'][0]==signatures['after'][0]}")
    a.csv.parent.mkdir(parents=True,exist_ok=True)
    with a.csv.open("w",newline="") as o:
        w=csv.DictWriter(o,fieldnames=list(measurements[0]))
        w.writeheader();w.writerows(measurements)
    a.disasm.parent.mkdir(parents=True,exist_ok=True)
    a.disasm.write_text("\n".join(evidence))
    print(f"R46_RECORDS={len(measurements)},cpu={cpu},csv={a.csv},disasm={a.disasm}")
    return 0
if __name__=="__main__":
    raise SystemExit(main())
