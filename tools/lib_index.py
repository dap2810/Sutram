#!/usr/bin/env python3
"""ROUND-52 WS3: the library index the compiler's `yoj` hint reads.

    python3 tools/lib_index.py --write    # writes src/r52_lib_index.inc from lib/*.smlib
    python3 tools/lib_index.py --check    # exit 1 if src/r52_lib_index.inc is not what --write would write

For every `prakriya <name>(` in lib/<module>.smlib, one (name, module) row, sorted by name then module. When a
call names no function the program defines or brings in, the compiler looks the name up here and, for each module
that has it, prints one hint line: bring that module in with `yoj`. The file is generated - edit lib/, then
--write - and pinned with the compiler (tools/r69_build.lock.json), like src/r11_sandesh.inc.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'src' / 'r52_lib_index.inc'
DECL = re.compile(r'^\s*prakriya\s+([A-Za-z_][A-Za-z0-9_]*)\s*\(', re.M)


def rows() -> list[tuple[str, str]]:
    out = set()
    for f in sorted((ROOT / 'lib').glob('*.smlib')):
        for m in DECL.finditer(f.read_text(encoding='utf-8')):
            out.add((m.group(1), f.stem))
    return sorted(out)


def render() -> str:
    r = rows()
    lines = ['; GENERATED by tools/lib_index.py from lib/*.smlib - do not edit by hand; run it with --write.',
             f'; R52: {len(r)} library prakriya, (name, module), for the `yoj` hint after `agyat prakriya`.',
             'section .data',
             'r52_lib_index:']
    lines += [f'    dq r52_li_{i}_n, r52_li_{i}_m' for i in range(len(r))]
    lines += ['    dq 0, 0']
    for i, (name, mod) in enumerate(r):
        lines.append(f'r52_li_{i}_n db "{name}", 0')
        lines.append(f'r52_li_{i}_m db "{mod}", 0')
    lines += ['section .text', '']
    return '\n'.join(lines)


def main(argv) -> int:
    text = render()
    if '--write' in argv:
        OUT.write_text(text, encoding='utf-8')
        print(f'wrote {OUT.relative_to(ROOT)}: {len(rows())} library prakriya')
        return 0
    if '--check' in argv:
        ok = OUT.exists() and OUT.read_text(encoding='utf-8') == text
        print(f'lib index: {len(rows())} library prakriya, ' + ('in step with lib/' if ok else
              'NOT in step with lib/ - run tools/lib_index.py --write'))
        return 0 if ok else 1
    print(__doc__)
    return 2


if __name__ == '__main__':
    raise SystemExit(main(sys.argv[1:]))
