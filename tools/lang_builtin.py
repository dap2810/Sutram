#!/usr/bin/env python3
"""ROUND-22 (F8): the eleven keyword packs, built into the compiler.

A language pack has two halves:
  * its MESSAGES (lang/<pack>.sandesh), assembled into the compiler since R11
    (src/r11_sandesh.inc), so they are always there;
  * its KEYWORDS (lang/<pack>.lang: "<native word> <sanskrit keyword>" per line),
    which the compiler read only from disk: ./lang/, beside the .exe on Windows,
    $HOME/.local/share/sutram/lang/.

When the .lang file was not on any of those paths, `--lang hindi` printed
"language pack not found: hindi" in Hindi, because the messages had loaded. That was
F8: the warning was about the file, the user read it as the language. The compiler
now falls back to a built-in copy of each .lang file, so the warning fires only for a
name that is no pack at all. A .lang file on disk still wins (a user can edit one).

This tool writes src/r22_lang_builtin.inc from lang/*.lang, byte for byte, so the
compiler source stays self-contained (tools/r69_build.py pins it like the other
includes), and --check refuses a stale copy.

usage:
  python3 -B tools/lang_builtin.py --write
  python3 -B tools/lang_builtin.py --check     # exit 1 if the include is not lang/*.lang
"""
from __future__ import annotations

import sys
from pathlib import Path

sys.dont_write_bytecode = True
ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'src/r22_lang_builtin.inc'
# The order of lang_names in src/sutram_compiler.asm: index 0 is "no pack".
PACKS = ['bengali', 'gujarati', 'hindi', 'kannada', 'malayalam', 'marathi', 'odia',
         'punjabi', 'tamil', 'telugu', 'sanskrit']
LIMIT = 16384   # lang_file_buf in src/sutram_compiler.asm


def render() -> str:
    lines = ['; GENERATED by tools/lang_builtin.py from lang/*.lang - do not edit.',
             '; ROUND-22 (F8): the keyword packs, built in. Indexed like lang_names.',
             '    lang_builtin_ptr:',
             '        dq 0, ' + ', '.join('r22_lb_%d' % i for i in range(1, len(PACKS) + 1)),
             '    lang_builtin_len:',
             '        dq 0, ' + ', '.join('r22_lb_%d_end - r22_lb_%d' % (i, i) for i in range(1, len(PACKS) + 1))]
    for i, name in enumerate(PACKS, 1):
        data = (ROOT / 'lang' / (name + '.lang')).read_bytes()
        if not data or len(data) > LIMIT:
            raise SystemExit('lang/%s.lang: %d bytes (must be 1..%d)' % (name, len(data), LIMIT))
        lines.append('    ; lang/%s.lang, %d bytes' % (name, len(data)))
        lines.append('    r22_lb_%d:' % i)
        for k in range(0, len(data), 32):
            lines.append('        db ' + ','.join(str(b) for b in data[k:k + 32]))
        lines.append('    r22_lb_%d_end:' % i)
    return '\n'.join(lines) + '\n'


def main(argv) -> int:
    text = render()
    if '--write' in argv:
        OUT.write_text(text, encoding='ascii', newline='\n')
        print('wrote %s: %d packs' % (OUT.relative_to(ROOT), len(PACKS)))
        return 0
    if '--check' in argv:
        if not OUT.exists() or OUT.read_text(encoding='ascii') != text:
            print('STALE: %s is not lang/*.lang; run tools/lang_builtin.py --write' % OUT.relative_to(ROOT))
            return 1
        print('BUILT-IN PACKS CURRENT: %d keyword packs' % len(PACKS))
        return 0
    print(__doc__)
    return 2


if __name__ == '__main__':
    raise SystemExit(main(sys.argv[1:]))
